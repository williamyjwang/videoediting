import {chromium} from 'playwright';
import assert from 'node:assert/strict';

const browser = await chromium.launch({executablePath: process.env.REMOTION_BROWSER_EXECUTABLE || '/usr/bin/chromium', headless: true, args: ['--no-sandbox']});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 1080}});
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto(process.env.MCC_TEST_ORIGIN || 'http://127.0.0.1:3001/');
  await page.getByRole('heading', {name: 'Start with your footage'}).waitFor();
  await page.screenshot({path: '.data/studio-desktop.png', fullPage: true});
  await page.getByRole('button', {name: 'Explore with a sample'}).click();
  await page.getByLabel('Project title').waitFor();
  await page.getByLabel('Opening hook').fill('A considered edit.');
  await page.getByRole('button', {name: 'Save edit', exact: true}).click();
  await page.getByText('Edit plan saved.', {exact: true}).waitFor();
  assert.equal(await page.getByLabel('Opening hook').inputValue(), 'A considered edit.');
  await page.getByRole('button', {name: 'Bilingual captions', exact: true}).click();
  await page.getByLabel('Chinese caption 1', {exact: true}).fill('可直接修改的中文字幕。');
  await page.getByLabel('Caption 1 end', {exact: true}).fill('2');
  assert.equal(await page.getByRole('button', {name: 'Render MP4'}).isDisabled(), true, 'Overlapping captions must prevent rendering');
  await page.getByRole('button', {name: 'Undo', exact: true}).click();
  await page.getByLabel('Output preset', {exact: true}).selectOption('landscape');
  await page.getByRole('button', {name: 'Undo', exact: true}).click();
  assert.equal(await page.getByLabel('Output preset', {exact: true}).inputValue(), 'vertical');
  await page.getByRole('button', {name: 'Redo', exact: true}).click();
  await page.getByLabel('Feedback for the next AI edit', {exact: true}).fill('Keep complete thoughts.');
  await page.getByRole('button', {name: 'Save edit', exact: true}).click();
  await page.getByText('Edit plan saved.', {exact: true}).waitFor();
  await page.reload();
  await page.getByLabel('Project title').waitFor();
  assert.equal(await page.getByLabel('Output preset', {exact: true}).inputValue(), 'landscape');
  assert.equal(await page.getByLabel('Feedback for the next AI edit', {exact: true}).inputValue(), 'Keep complete thoughts.');
  await page.getByRole('button', {name: 'Bilingual captions', exact: true}).click();
  assert.equal(await page.getByLabel('Chinese caption 1', {exact: true}).inputValue(), '可直接修改的中文字幕。');
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', {name: 'Download bilingual SRT', exact: true}).click();
  assert.equal((await downloaded).suggestedFilename(), 'mcc-bilingual.srt');
  await page.screenshot({path: '.data/studio-sample.png', fullPage: true});
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: '.data/studio-mobile.png', fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile layout should fit');
  assert.deepEqual(errors, []);
  console.log('PASS: studio loads, sample project, Remotion preview, hook and bilingual subtitle editing, overlap protection, output presets, undo/redo, SRT download, reload persistence, and mobile layout. No browser exceptions.');
} finally {await browser.close();}
